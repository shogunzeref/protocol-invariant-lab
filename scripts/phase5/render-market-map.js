// Renders research/morpho-pendle-market-map.md from the read-only scan in
// research/data/morpho-pt-markets.json.
//
//   node scripts/phase5/render-market-map.js

const fs = require("fs");
const path = require("path");

const DATA = path.join(__dirname, "../../research/data/morpho-pt-markets.json");
const OUT = path.join(__dirname, "../../research/morpho-pendle-market-map.md");

const scan = JSON.parse(fs.readFileSync(DATA, "utf8"));

const usd = (x) =>
  x === null || x === undefined ? "UNKNOWN" : "$" + Math.round(x).toLocaleString("en-US");
const pct = (x) => (x === null || x === undefined ? "UNKNOWN" : (x * 100).toFixed(1) + "%");
const iso = (t) => (t ? new Date(t * 1000).toISOString().slice(0, 10) : "UNKNOWN");
const short = (a) => (a ? `${a.slice(0, 10)}...${a.slice(-4)}` : "UNKNOWN");

const markets = (scan.markets || []).filter((m) => !m.error);
markets.sort((a, b) => (b.state?.collateralAssetsUsd || 0) - (a.state?.collateralAssetsUsd || 0));

const lines = [];
const w = (s = "") => lines.push(s);

w("# Morpho Blue markets with Pendle PT collateral -- market map");
w();
w("Generated by `scripts/phase5/render-market-map.js` from");
w("`research/data/morpho-pt-markets.json`, which was produced by");
w("`scripts/phase5/scan-morpho-pt-markets.js`.");
w();
w("Every value here came from a read-only `eth_call` against the deployed");
w("contract, or from the Morpho GraphQL indexer where marked. No transaction was");
w("sent, no state was modified, and no position was opened.");
w();
w(`- Scan timestamp: \`${scan.generatedAt}\``);
w(`- Markets discovered: **${markets.length}**`);
w("- Chain heads at scan time:");
for (const [chain, head] of Object.entries(scan.chainHeads || {})) {
  w(`  - ${chain}: \`${head}\``);
}
w();
w("## PT pricing mechanism distribution");
w();
w("Mechanism is determined by recursively probing the deployed oracle with");
w("`eth_call` and identifying each node by its actual function selectors -- not by");
w("the indexer's label and not by the contract name.");
w();
w("| PT price mechanism | Markets |");
w("| --- | --- |");
for (const [k, v] of Object.entries(scan.mechanismDistribution || {})) {
  w(`| \`${k}\` | ${v} |`);
}
w();

// ---------------------------------------------------------------- FACTS table
w("## FACTS: market parameters");
w();
w("`LLTV` is read from the Morpho market params. `Collateral`/`Borrowed` are USD");
w("figures from the Morpho indexer and are therefore the one column here that is");
w("not a direct chain read.");
w();
w("| Chain | Collateral | Loan | LLTV | Maturity | Collateral supplied | Borrowed | Market ID |");
w("| --- | --- | --- | --- | --- | --- | --- | --- |");
// Maturity comes from the Pendle market's `expiry()` where a market is attached,
// otherwise from the linear-discount oracle's own `maturity()` -- markets whose
// only PT leg is a discount feed have no Pendle market in the oracle path at all.
const maturityOf = (m) =>
  Object.values(m.pendleMarkets || {})
    .map((p) => p.expiry)
    .find(Boolean) ?? (m.ptPriceLeaves || []).map((l) => l.maturity).find(Boolean);

for (const m of markets) {
  const maturity = maturityOf(m);
  w(
    `| ${m.chain} | ${m.collateral.symbol} | ${m.loan.symbol} | ${pct(m.lltvFraction)} | ` +
      `${iso(maturity)} | ${usd(m.state?.collateralAssetsUsd)} | ${usd(m.state?.borrowAssetsUsd)} | ` +
      `\`${short(m.marketId)}\` |`
  );
}
w();

// ------------------------------------------------------------- oracle wiring
w("## FACTS: oracle wiring");
w();
w("`Oracle` is the address Morpho calls. `Path` is the classified chain of");
w("contracts beneath it, each node identified by probing its selectors.");
w();
w("| Chain | Collateral | Loan | Oracle | IRM | Path |");
w("| --- | --- | --- | --- | --- | --- |");
for (const m of markets) {
  w(
    `| ${m.chain} | ${m.collateral.symbol} | ${m.loan.symbol} | ` +
      `\`${short(m.oracleAdapter || m.oraclePath?.address)}\` | \`${short(m.irm)}\` | ` +
      `${(m.oraclePathKinds || []).join(" > ") || "UNKNOWN"} |`
  );
}
w();

// ------------------------------------------------------- Pendle market state
w("## FACTS: Pendle market state behind each PT feed");
w();
w("Reserves are in the token's own base units, as returned by");
w("`PendleMarket.readState(address(0))`. `lastLnImpliedRate` is the stored");
w("logarithmic implied rate the TWAP oracles average over.");
w();
w("| Pendle market | Expiry | totalPt | totalSy | lastLnImpliedRate | scalarRoot | lnFeeRateRoot | TWAP obs. cardinality |");
w("| --- | --- | --- | --- | --- | --- | --- | --- |");
const seen = new Set();
for (const m of markets) {
  for (const [addr, p] of Object.entries(m.pendleMarkets || {})) {
    if (seen.has(addr) || p.error) continue;
    seen.add(addr);
    w(
      `| \`${short(addr)}\` | ${iso(p.expiry)} | ${p.totalPt} | ${p.totalSy} | ` +
        `${p.lastLnImpliedRate} | ${p.scalarRoot} | ${p.lnFeeRateRoot} | ` +
        `${p.observationCardinality ?? "UNKNOWN"} |`
    );
  }
}
w();

// ------------------------------------------------------------------ defences
w("## FACTS: manipulation-resistance layers per market");
w();
w("`Spot reads` counts oracle legs that read live market state with **no** time");
w("weighting. In the lab's Moola phases that count was 1, and that is precisely");
w("what made the earlier attack work. Here it is 0 everywhere.");
w();
w("| Chain | Collateral | Loan | TWAP windows (s) | Market-independent legs | min() aggregations | Yield caps | Deviation timelocks | Spot reads |");
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- |");
for (const m of markets) {
  const d = m.defences || {};
  w(
    `| ${m.chain} | ${m.collateral.symbol} | ${m.loan.symbol} | ` +
      `${(d.twapWindows || []).join(", ") || "-"} | ${d.marketIndependentFeeds ?? 0} | ` +
      `${d.minAggregations ?? 0} | ${(d.yieldCaps || []).length} | ` +
      `${(d.deviationTimelocks || []).length} | ${d.spotMarketReads ?? 0} |`
  );
}
w();

// ---------------------------------------------------------------- INFERENCES
w("## INFERENCES");
w();
w("Labelled as inference because they combine several confirmed reads with an");
w("interpretation that the reads alone do not force.");
w();
const twapDurations = new Set();
for (const m of markets) for (const d of m.defences?.twapWindows || []) twapDurations.add(d);
w(
  `- **No live PT market prices collateral from an untimed AMM spot read.** Across ` +
    `${markets.length} markets the classified paths contain ` +
    `${[...twapDurations].sort((a, b) => a - b).join("s / ")}s TWAP windows, ` +
    `market-independent linear-discount feeds, or both. Inference rather than ` +
    "fact only because 9 paths terminate in an external feed whose internals " +
    "were not verifiable (see UNKNOWN)."
);
w(
  "- **The `min()` aggregation in the Ojo PT feeds is the binding defence, not the " +
    "TWAP.** A feed that reports `min(twap, linearDiscount)` cannot be raised by " +
    "buying PT unless the TWAP leg is already the lower of the two -- and buying " +
    "raises it toward the discount leg, at which point the discount leg caps it."
);
w(
  "- **The linear-discount feeds are deliberately conservative, not merely " +
    "manipulation-resistant.** They report `1 - discount * T`, a straight line " +
    "strictly below the exponential the market prices, so borrowers on those " +
    "markets systematically receive less capacity than the PT is worth."
);
w(
  "- **The MetaOracle deviation timelocks are a governance circuit breaker, not a " +
    "price filter.** They compare a primary and backup feed and gate switching " +
    "between them behind a challenge/healing delay, which bounds how fast a " +
    "compromised feed can take effect but does not smooth an individual feed."
);
w();

// ------------------------------------------------------------------- UNKNOWN
w("## UNKNOWN");
w();
const unknownMarkets = markets.filter((m) => m.ptPriceMechanism === "UNKNOWN");
w(
  `- **${unknownMarkets.length} markets terminate in an external feed whose pricing ` +
    "logic was not verifiable.** The feed address and its `description()` are " +
    "readable, but without verified source the exact mechanism, observation " +
    "window and deviation limits are unknown. These markets are excluded from " +
    "the quantitative conclusions:"
);
// The terminal feeds are Chainlink-compatible, so `description()` is readable
// even without verified source. It is the only self-reported evidence available
// about what these feeds actually do, so it is quoted verbatim rather than
// paraphrased -- and it is self-reported, not verified.
const descriptionsOf = (node, out = []) => {
  if (!node || typeof node !== "object") return out;
  if (node.description) out.push(node.description);
  for (const v of Object.values(node)) {
    if (Array.isArray(v)) v.forEach((x) => descriptionsOf(x, out));
    else if (v && typeof v === "object") descriptionsOf(v, out);
  }
  return out;
};
for (const m of unknownMarkets) {
  const path = m.oraclePathKinds || [];
  w(`  - ${m.chain} ${m.collateral.symbol}/${m.loan.symbol} -- path \`${path.join(" > ")}\``);
  for (const d of [...new Set(descriptionsOf(m.oraclePath))]) {
    w(`    - self-reported \`description()\`: "${d}"`);
  }
}
w(
  "  Two of those self-reported descriptions are worth noting. The kHYPE feeds " +
    'describe themselves as a "Pendle Hype/KHype exchange rate" composed with ' +
    "RedStone feeds, which suggests an exchange-rate rather than an AMM-spot " +
    "source; and the Katana feed describes itself as a TWAP that is *upper " +
    'bounded by the redemption value*. That last phrase is an independent, ' +
    "third-party statement of the same par ceiling this phase derives from the " +
    "Pendle AMM source. Neither description was verified against source, so " +
    "both remain UNKNOWN."
);
w(
  "- **Reserve fee overrides.** `readState` was called with router `address(0)`, " +
    "which returns the non-overridden fee. A whitelisted router may trade more " +
    "cheaply, so the modelled displacement costs are upper bounds on the fee " +
    "component, not exact figures for every caller."
);
w(
  "- **Off-chain keeper behaviour.** Whether and how quickly the MetaOracle " +
    "primary/backup switch is exercised in practice is a matter of operator " +
    "policy and is not observable from chain state."
);
w(
  "- **Liquidator capacity.** The unwind discounts modelled here assume the whole " +
    "position exits through its own Pendle pool. Real liquidators may have access " +
    "to other venues, OTC flow, or the ability to hold to maturity, all of which " +
    "would improve on the modelled figure. The modelled figure is therefore " +
    "conservative."
);
w();

fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`Wrote ${OUT} (${lines.length} lines, ${markets.length} markets)`);
